public class Ornek2 {
    // Ekrana 10'dan 1'e kadar olan sayilari tersten yazdir.
    public static void main(String[] args) {
        System.out.println("Dongu baslatiliyor!");
        for (int i = 10; i > 0; i--) {
            System.out.println(i);
        }
        System.out.println("Dongu bitti!");
    }

}
